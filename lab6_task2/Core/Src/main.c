// Hardware Input Capture Callback (triggers automatically on PA0 edge)
void HAL_TIM_IC_CaptureCallback(TIM_HandleTypeDef *htim)
{
    if (htim->Instance == TIM2 && htim->Channel == HAL_TIM_ACTIVE_CHANNEL_1)
    {
        if (is_first_captured == 0)
        {
            val1 = HAL_TIM_ReadCapturedValue(htim, TIM_CHANNEL_1);
            is_first_captured = 1;
        }
        else
        {
            val2 = HAL_TIM_ReadCapturedValue(htim, TIM_CHANNEL_1);

            if (val2 >= val1) {
                diff = val2 - val1;
            } else {
                diff = (0xFFFFFFFF - val1) + val2 + 1; // Counter overflow handling
            }

            val1 = val2;
        }
        last_capture_tick = HAL_GetTick(); // Record timestamp of last active pulse
    }
}
